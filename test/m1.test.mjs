import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { cpSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import test from 'node:test'
import { harness, until } from './harness.mjs'

test('project identity, marker precedence, longest registered prefix, move and conflict', async t => {
  const h = harness(t)
  await assert.rejects(h.cli('ls'), /cc-bro init/)
  execFileSync('git',['init','-q'],{cwd:h.cwd})
  await assert.rejects(h.json('init'), /Choose allowed workers/)
  await assert.rejects(h.json('init','--allow','codex,pi:deepseek'), /Choose a default/)
  await assert.rejects(h.json('init','--allow','claude'), /Expected codex or pi/)
  const parent = await h.json('init','--allow','codex')
  assert.equal(parent.worker,'codex')
  assert.deepEqual(parent.allow,['codex'])
  assert.deepEqual(readdirSync(join(h.cwd,'.cc-bro')).sort(),['.gitignore','project-id'])
  assert.equal(execFileSync('git',['status','--porcelain'],{cwd:h.cwd,encoding:'utf8'}),'')
  const nested = join(h.cwd,'nested'), child = join(nested,'src')
  mkdirSync(child,{recursive:true})
  const other = JSON.parse(await h.at(nested,'init','--allow','pi:deepseek','--default-worker','pi:deepseek','--json'))
  await h.at(child,'say','same','nested')
  rmSync(join(nested,'.cc-bro'),{recursive:true})
  assert.deepEqual(await h.at(child,'ls','--json'),'[]')
  rmSync(join(h.cwd,'.cc-bro'),{recursive:true})
  assert.equal(JSON.parse(await h.at(child,'ls','--json'))[0].provider,'pi:deepseek')
  assert.equal(JSON.parse(await h.at(nested,'init','--json')).id, other.id)
  assert.equal((await h.json('init')).id,parent.id)
  const moved = join(h.base,'moved'), copied = join(h.base,'copied')
  renameSync(nested,moved)
  assert.equal(JSON.parse(await h.at(moved,'show','same','--json')).reply,'nested')
  cpSync(moved,copied,{recursive:true})
  await assert.rejects(h.at(copied,'ls'),/already bound/)
  const unrelated = join(h.base,'work-2')
  mkdirSync(unrelated)
  await assert.rejects(h.at(unrelated,'ls'),/cc-bro init/)
  symlinkSync(join(moved,'.cc-bro'),join(unrelated,'.cc-bro'))
  await assert.rejects(h.at(unrelated,'init'),/Expected a .cc-bro directory/)
})

test('one active turn per name, durable queue, deny before dispatch, inspect and accept', async t => {
  const h = harness(t,false,{CC_BRO_CONCURRENCY:'1'})
  const p = await h.json('init','--allow','codex,pi:deepseek','--default-worker','codex')
  const replies = await Promise.all([1,2,3].map(() => h.json('say','one','hold','--bg')))
  assert.equal(replies.filter(r => r.outcome === 'injected').length,2)
  assert.ok(replies.every(r => r.turn === 1))
  assert.equal((await h.json('say','two','hello','--bg','--worker','pi:deepseek')).kind,'queued')
  await assert.rejects(h.cli('say','blocked','x','--worker','deepseek'),/not allowed/)
  await assert.rejects(h.cli('say','blocked','x','--worker','pi:other'),/not allowed/)
  await assert.rejects(h.cli('say','blocked','x','--model','deepseek/model'),/provider/)
  assert.equal((await h.json('ls')).length,2)
  await until(() => h.query("SELECT native_id FROM conversations WHERE name='one'")[0]?.native_id)
  process.kill(await h.runnerPid(),'SIGKILL')
  await h.json('ls')
  await assert.rejects(h.cli('wait','one','1'),/interrupted/)
  assert.equal(await h.cli('wait','two','1'),'hello')
  const first = await h.json('show','two')
  assert.equal(first.cachedInputTokens,32)
  assert.equal((await h.json('say','two','again')).turn,2)
  assert.equal((await h.json('show','two')).session,first.session)
  await assert.rejects(h.cli('say','two','new','--worker','codex'),/bound/)
  await h.cli('done','two')
  const url = await h.cli('ui','--no-open')
  const detail = await (await fetch(url+'/api/projects/'+p.id+'/tickets/two')).json()
  assert.equal(detail.status,'done')
  assert.equal(detail.lastReply,'again')
  assert.ok(detail.timeline.some(e => e.turn === 2 && e.kind === 'usage'))
  assert.equal((await fetch(url+'/api/pi')).status,404)
})

test('exec fallback resumes by explicit ID; no fallback after a submitted app-server turn', async t => {
  const h = harness(t)
  await h.cli('init','--allow','codex')
  await assert.rejects(h.cli('say','broken','disconnect'),/closed|exited/)
  assert.equal(readFileSync(join(h.cwd,'starts'),'utf8').trim().split('\n').length,1)
  writeFileSync(join(h.cwd,'exec-only'),'')
  assert.equal((await h.json('say','fallback','one')).reply,'one')
  const first = await h.json('show','fallback')
  assert.equal(first.transport,'exec')
  assert.equal(first.cachedInputTokens,64)
  await h.cli('shutdown')
  assert.equal((await h.json('say','fallback','two')).reply,'two')
  assert.equal((await h.json('show','fallback')).session,first.session)
})

test('stop releases a slot; a revoked queued worker never receives the prompt', async t => {
  const h = harness(t,false,{CC_BRO_CONCURRENCY:'1'})
  await h.cli('init','--allow','codex,pi:deepseek','--default-worker','codex')
  await h.cli('say','busy','hold','--bg')
  await h.cli('say','queued','private','--worker','pi:deepseek','--bg')
  await h.cli('init','--allow','codex')
  await h.cli('stop','busy')
  await assert.rejects(h.cli('wait','queued','1'),/no longer allowed/)
  assert.equal((await h.json('show','queued')).session,null)
  assert.equal((await h.json('say','busy','ok')).reply,'ok')
})

test('upgrading a registered policy drops retired permissions without choosing a replacement default', async t => {
  const h = harness(t)
  await h.cli('init','--allow','pi:deepseek')
  await h.cli('say','old','remember original')
  await h.cli('shutdown')
  const { DatabaseSync } = await import('node:sqlite')
  const db = new DatabaseSync(join(h.data,'registry-v2.sqlite'))
  db.prepare('UPDATE projects SET allow=?,worker=?').run(JSON.stringify(['claude','pi:deepseek','codex']), 'claude')
  db.close()
  await assert.rejects(h.cli('say','new','test'), /allowed|default/)
  await assert.rejects(h.cli('say','new','test','--worker','claude'), /not allowed/)
  await assert.rejects(h.cli('init'), /Choose a default/)
  const project = await h.json('init','--default-worker','pi:deepseek')
  assert.deepEqual(project.allow,['pi:deepseek','codex'])
  assert.equal(await h.cli('say','old','recall'),'original')
})
