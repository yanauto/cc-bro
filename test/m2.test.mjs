import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import test from 'node:test'
import { baseline, changes } from '../lib/worktree.mjs'
import { harness, until } from './harness.mjs'

function repository(cwd) {
  const git = (...args) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim()
  git('init', '-q')
  writeFileSync(join(cwd, 'base'), 'initial\n')
  git('add', 'base')
  git('-c', 'user.name=Fixture', '-c', 'user.email=fixture@localhost', 'commit', '-qm', 'Seed')
  return git
}

test('steer acknowledges the expected turn; decline queues and stop resolves deferred waiters', async t => {
  const h = harness(t)
  await h.cli('init','--allow','codex,pi:deepseek','--default-worker','codex')
  await h.cli('say', 'one', 'hold', '--bg')
  assert.equal((await h.json('say', 'one', 'add this', '--bg')).outcome, 'injected')
  const next = await h.json('say', 'one', 'decline', '--bg')
  assert.deepEqual([next.outcome, next.turn], ['queued', 2])
  await assert.rejects(h.json('say','one','no','--worker','pi:deepseek','--bg'), err => JSON.parse(err.stdout).outcome === 'rejected')
  await h.cli('stop', 'one')
  await assert.rejects(h.cli('wait', 'one', '2'), /Previous turn did not complete/)
  const after = await h.json('show', 'one')
  assert.deepEqual(after.interjections.map(i => i.outcome), ['injected', 'queued', 'rejected', 'rejected'])
  assert.equal((await h.json('say', 'one', 'retry')).turn, 3)
})

test('pi confirms delivered steers, durably defers declined messages in order and resumes the same session', async t => {
  const h = harness(t)
  await h.cli('init','--allow','pi:deepseek')
  await h.cli('say','writer','hold','--bg')
  const initial = await h.json('show','writer')
  assert.equal(initial.model,'deepseek/fixture-default')
  assert.equal(initial.transport,'pi-rpc')
  const injected = await h.json('say','writer','clarification','--bg')
  assert.equal(injected.outcome,'injected')
  const a = await h.json('say','writer','reject steer one','--bg')
  const b = await h.json('say','writer','reject steer two','--bg')
  assert.deepEqual([a.outcome,b.outcome,a.turn,b.turn], ['queued','queued',2,2])
  writeFileSync(join(h.cwd,'release'),'go')
  assert.equal((await h.json('wait','writer','1')).reply,'clarification')
  assert.equal((await h.json('wait','writer','2')).reply,'reject steer one\n\nreject steer two')
  await h.cli('shutdown')
  await h.cli('say','writer','again')
  const r = await h.json('show','writer')
  assert.equal(r.session,initial.session)
  assert.equal(r.cacheRatio,0.5)
  assert.equal(r.interjections.length,3)
})

test('pi recovers a steer that missed settling and distinguishes cancellation from delivery', async t => {
  const h = harness(t)
  await h.cli('init','--allow','pi:deepseek')
  await h.cli('say','late','late','--bg')
  const next = await h.json('say','late','carry forward','--bg')
  assert.deepEqual([next.outcome,next.turn],['queued',2])
  assert.equal(await h.cli('wait','late','2'),'carry forward')
  await h.cli('say','late','hold','--bg')
  const pending = h.follow('say','late','pending','--bg','--json')
  await until(() => h.query("SELECT 1 FROM messages WHERE kind='pending' AND content='pending'").length)
  await h.cli('stop','late')
  await until(() => pending.stdout.includes('rejected'))
  assert.equal((await h.json('show','late')).interjections.at(-1).outcome,'rejected')
})

test('pi discards an unconfirmed runtime queue before reusing its persistent session', async t => {
  const h = harness(t)
  await h.cli('init','--allow','pi:deepseek')
  await h.cli('say','writer','uncleared','--bg')
  const pid = h.query('SELECT worker_pid FROM conversations')[0].worker_pid
  await assert.rejects(h.json('say','writer','unconfirmed','--bg'), err => JSON.parse(err.stdout).outcome === 'rejected')
  assert.equal((await h.json('wait','writer','1')).reply,'original turn')
  const old = await h.json('show','writer')
  assert.equal(await h.cli('say','writer','new request'),'new request')
  assert.equal((await h.json('show','writer')).session,old.session)
  assert.notEqual(h.query('SELECT worker_pid FROM conversations')[0].worker_pid,pid)
})

test('worktree isolates edits, links cross-vendor review to a completed turn, survives acceptance', async t => {
  const h = harness(t)
  const git = repository(h.cwd)
  await h.cli('init','--allow','codex,pi:deepseek','--default-worker','codex')
  await h.cli('say','feature','write fixture','--worktree')
  const p = await h.json('show','feature')
  assert.match(p.branch,/^cc-bro\/feature-/)
  assert.ok(p.changedFiles.some(f => f.status === 'A' && f.path === 'proof file.txt'))
  assert.equal(p.cacheRatio,0.25)
  assert.equal(git('status','--porcelain'),'')
  assert.equal(readFileSync(join(p.worktree,'proof file.txt'),'utf8'),'proof')
  await assert.rejects(h.cli('review','feature','--by','codex'),/different worker/)
  await assert.rejects(h.cli('review','feature','--by','pi:other','--model','other/a'),/not allowed/)
  await assert.rejects(h.cli('review','feature','--by','claude'),/Choose --by codex or pi/)
  const r = await h.json('review','feature','--by','pi:deepseek')
  const child = await h.json('show',r.name)
  assert.equal(child.parent,'feature')
  assert.equal(child.parentTurn,1)
  assert.equal(child.worktree,p.worktree)
  assert.match(r.reply,/Writer final reply:\nwrite fixture/)
  assert.match(r.reply,/A "proof file.txt"/)
  assert.match(r.reply,/Writer instructions for this turn:\nwrite fixture/)
  assert.equal(child.changedFiles.length,0)
  assert.notEqual(child.session,p.session)
  assert.ok(!(await h.json('done',r.name)).cleanupHint)
  await h.cli('shutdown')
  const linked = JSON.parse(await h.at(p.worktree,'show','feature','--json'))
  assert.deepEqual(linked.reviews,[{ id:r.name,turn:1 }])
  assert.match(await h.cli('done','feature'),/remove the worktree manually/)
  assert.ok(existsSync(p.worktree))
  assert.ok(git('branch','--list',p.branch).includes(p.branch))
  git('worktree','remove','--force',p.worktree)
  await assert.rejects(h.cli('say','feature','lost tree'),/ENOENT|worktree/)
  assert.equal(git('status','--porcelain'),'')
})

test('git change summary includes staged-only edits, committed changes and untracked paths; ignores initial dirt', t => {
  const h = harness(t)
  const git = repository(h.cwd)
  writeFileSync(join(h.cwd,'unrelated'), 'manager notes')
  const b = baseline(h.cwd)
  writeFileSync(join(h.cwd,'base'), 'staged\n')
  git('add','base')
  writeFileSync(join(h.cwd,'base'), 'initial\n')
  assert.deepEqual(changes(h.cwd,b), [{path:'base',status:'M'}])
  writeFileSync(join(h.cwd,'two\nlines'),'payload')
  git('add','two\nlines')
  git('-c','user.name=Fixture','-c','user.email=fixture@localhost','commit','-qm','Rename-safe fixture')
  rmSync(join(h.cwd,'base'))
  writeFileSync(join(h.cwd,'new file'),'new')
  assert.deepEqual(changes(h.cwd,b), [{path:'base',status:'D'},{path:'new file',status:'A'},{path:'two\nlines',status:'A'}])
})

test('Codex RPC refusal resumes exactly once; an unknown acknowledgement is never replayed', async t => {
  const h = harness(t)
  await h.cli('init','--allow','codex,pi:deepseek','--default-worker','codex')
  await h.cli('say','one','hold','--bg')
  const first = await h.json('say','one','decline','--bg')
  assert.equal(first.outcome,'queued')
  await assert.rejects(h.json('say','one','unknown ack','--bg'), err => {
    const r = JSON.parse(err.stdout)
    return r.outcome === 'rejected' && r.turn === 1 && /unconfirmed/i.test(r.reason)
  })
  const finish = await h.json('say','one','finish')
  assert.deepEqual([finish.outcome,finish.turn,finish.reply],['injected',1,'released'])
  assert.equal((await h.json('wait','one','2')).reply,'decline')
  assert.equal(readFileSync(join(h.cwd,'starts'),'utf8').trim().split('\n').length,2)
})

test('queued follow-up survives runner loss while waiting for its name’s first slot', async t => {
  const h = harness(t,false,{CC_BRO_CONCURRENCY:'1'})
  await h.cli('init','--allow','codex,pi:deepseek','--default-worker','codex')
  await h.cli('say','blocker','hold','--bg')
  await h.cli('say','waiting','first','--worker','pi:deepseek','--bg')
  assert.equal((await h.json('say','waiting','second','--bg')).turn,2)
  process.kill(await h.runnerPid(),'SIGKILL')
  assert.equal((await h.json('wait','waiting','1')).reply,'first')
  assert.equal((await h.json('wait','waiting','2')).reply,'second')
})

test('after a runner crash a pending pi steer has one rejected receipt and is never replayed', async t => {
  const h = harness(t)
  await h.cli('init','--allow','pi:deepseek')
  await h.cli('say','writer','hold','--bg')
  const pending = h.follow('say','writer','pending','--bg')
  await until(() => h.query("SELECT 1 FROM messages WHERE kind='pending'").length)
  process.kill(await h.runnerPid(),'SIGKILL')
  await until(() => pending.child.exitCode !== null)
  const r = await h.json('show','writer')
  assert.deepEqual(r.interjections.map(i => [i.number,i.outcome]),[[2,'rejected']])
  assert.equal(r.status,'error')
  assert.equal((await h.json('say','writer','recovered')).reply,'recovered')
  assert.equal(h.query("SELECT count(*) AS n FROM messages WHERE kind='next'")[0].n,0)
})
